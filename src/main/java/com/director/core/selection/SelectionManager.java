    private Box adjustBounds(Box base, int faceIndex, double offset) {
        if (base == null) {
            return null;
        }

        Box alignedBase = normalizeBlockAlignedBox(base);
        int minX = (int) alignedBase.minX;
        int minY = (int) alignedBase.minY;
        int minZ = (int) alignedBase.minZ;
        int maxX = (int) alignedBase.maxX;
        int maxY = (int) alignedBase.maxY;
        int maxZ = (int) alignedBase.maxZ;
        int snappedOffset = snapResizeOffsetToBlocks(offset);
        int minThickness = 1;

        switch (faceIndex) {
            case 0 -> maxX = Math.max(minX + minThickness, maxX + snappedOffset);
            case 1 -> minX = Math.min(maxX - minThickness, minX - snappedOffset);
            case 2 -> maxY = Math.max(minY + minThickness, maxY + snappedOffset);
            case 3 -> minY = Math.min(maxY - minThickness, minY - snappedOffset);
            case 4 -> maxZ = Math.max(minZ + minThickness, maxZ + snappedOffset);
            case 5 -> minZ = Math.min(maxZ - minThickness, minZ - snappedOffset);
            default -> {
            }
        }

        return new Box(minX, minY, minZ, maxX, maxY, maxZ);
    }

    private Box copyBox(Box source) {
        return source == null ? null : new Box(source.minX, source.minY, source.minZ,
                source.maxX, source.maxY, source.maxZ);
    }

    private Box normalizeBlockAlignedBox(Box source) {
        if (source == null) {
            return null;
        }

        int minX = (int) Math.floor(source.minX);
        int minY = (int) Math.floor(source.minY);
        int minZ = (int) Math.floor(source.minZ);
        int maxX = Math.max(minX + 1, (int) Math.ceil(source.maxX));
        int maxY = Math.max(minY + 1, (int) Math.ceil(source.maxY));
        int maxZ = Math.max(minZ + 1, (int) Math.ceil(source.maxZ));
        return new Box(minX, minY, minZ, maxX, maxY, maxZ);
    }

    private int snapResizeOffsetToBlocks(double offset) {
        if (offset >= 1.0) {
            return (int) Math.floor(offset);
        }
        if (offset <= -1.0) {
            return (int) Math.ceil(offset);
        }
        return 0;
    }
    
